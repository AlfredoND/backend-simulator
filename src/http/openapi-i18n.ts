/** Selects the requested summary, with explicit English and catalogue fallbacks. */
export function translateSummary(summary: string | undefined, summaryEn: string | undefined, lang: ApiLanguage): string {
  if (!summary) return '';
  if (lang === 'es') return summary;
  return summaryEn ?? SUMMARY_EN[summary] ?? summary;
}

function translateGenericDescription(description: string, lang: ApiLanguage): string | null {
  if (lang === 'es') return description;
  const resource = ENGLISH_RESOURCE_NAMES[description];
  if (resource) return resource.one;

  let match = /^Lista paginada de (.+)$/.exec(description);
  if (match) {
    const names = ENGLISH_RESOURCE_NAMES[match[1]];
    return `Paginated list of ${names?.many ?? match[1]}`;
  }

  match = /^Filtro exacto por (.+)\. Repetible para IN\.$/.exec(description);
  if (match) return `Exact filter by ${match[1]}. Repeat for IN.`;

  return DESCRIPTIONS_EN[description] ?? null;
}

/** Translates known response/parameter descriptions and generic patterns. */
export function translateDescription(description: string, lang: ApiLanguage): string {
  return translateGenericDescription(description, lang) ?? description;
}

/** Finds summaries that would still be Spanish in the English specification. */
export function missingEnglishSummaries(routes: Array<{ doc: { summary?: string; summaryEn?: string } }>): string[] {
  const missing = new Set<string>();
  for (const route of routes) {
    const summary = route.doc.summary;
    if (!summary) continue;
    if (!route.doc.summaryEn && !SUMMARY_EN[summary]) missing.add(summary);
  }
  return [...missing];
}
