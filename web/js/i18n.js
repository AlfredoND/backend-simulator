export function t(lang, key, params = {}) {
  const dictionary = messages[lang] ?? messages.es;
  const template = dictionary[key] ?? messages.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

function translatedAttribute(element, lang, attribute, setter) {
  const key = element.getAttribute(attribute);
  if (!key) return;
  setter(t(lang, key));
}

export function applyTranslations(root, lang) {
  document.documentElement.lang = lang;
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(lang, element.getAttribute('data-i18n'));
  }
  for (const element of root.querySelectorAll('[data-i18n-placeholder]')) {
    translatedAttribute(element, lang, 'data-i18n-placeholder', (text) => element.setAttribute('placeholder', text));
  }
  for (const element of root.querySelectorAll('[data-i18n-aria-label]')) {
    translatedAttribute(element, lang, 'data-i18n-aria-label', (text) => element.setAttribute('aria-label', text));
  }
  for (const element of root.querySelectorAll('[data-i18n-title]')) {
    translatedAttribute(element, lang, 'data-i18n-title', (text) => element.setAttribute('title', text));
  }
}
